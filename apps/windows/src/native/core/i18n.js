export const DICTS = { fa, en, de };
export const LANG_NAMES = { fa: 'فارسی', en: 'English', de: 'Deutsch' };

let current = 'fa';

export function setLang(lang) {
  current = DICTS[lang] ? lang : 'fa';
  document.documentElement.lang = current;
  document.documentElement.dir = DICTS[current].dir;
  return current;
}

export const lang = () => current;

export function t(key, ...args) {
  const value = DICTS[current][key] !== undefined ? DICTS[current][key] : fa[key];
  if (typeof value === 'function') return value(...args);
  return value !== undefined ? value : key;
}

/** Pick fa/en/de from a { fa, en, de } object. */
export const pick = (texts) => (texts && (texts[current] || texts.en || texts.fa)) || '';

/** Fill every [data-i18n] node. */
export function fillStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const text = t(node.dataset.i18n);
    if (typeof text === 'string') node.textContent = text;
  });
}
